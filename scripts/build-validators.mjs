// Ajv runs only at development/build time; browser validators never use eval.
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
const read = async (name) =>
  JSON.parse(
    await readFile(
      new URL(`../src/contracts/${name}`, import.meta.url),
      "utf8",
    ),
  );
const output = await read("ai-contracts.schema.json"),
  variables = await read("ai-variables.schema.json");
const ajv = new Ajv2020({
  strict: true,
  allErrors: true,
  code: { source: true, esm: true },
});
addFormats(ajv);
ajv.addSchema(output);
const names = {};
for (const name of ["AiResponse", "ReplayRecord", "A1", "A2", "A3", "A7"])
  names[name] = `${output.$id}#/$defs/${name}`;
for (const [module, schema] of Object.entries(variables)) {
  const id = `urn:careerpilot:variables:${module}:1.0`;
  ajv.addSchema(schema, id);
  names[`Input${module}`] = id;
}
let generated = standalone(ajv, names);
const imports = new Map();
generated = generated.replace(/require\("([^"\n]+)"\)/g, (_match, module) => {
  if (/^ajv(?:-formats)?\/dist\//.test(module) && !module.endsWith(".js")) module += ".js";
  if (!imports.has(module)) imports.set(module, `helper${imports.size}`);
    return imports.get(module);
});
const code =
  "// Generated by scripts/build-validators.mjs. Do not edit.\n" +
  [...imports]
    .map(([module, name]) => `import * as ${name}Module from ${JSON.stringify(module)};\nconst ${name} = ${name}Module.default && typeof ${name}Module.default === "object" ? ${name}Module.default : ${name}Module;`)
    .join("\n") +
  "\n" +
  generated +
  "\n";
const target = new URL(
  "../src/contracts/generated/ai-validators.js",
  import.meta.url,
);
await mkdir(fileURLToPath(new URL("./", target)), { recursive: true });
await writeFile(target, code);
console.log(
  "Precompiled AI validators · CSP-safe · no runtime code generation",
);
